// Timeline from the processing steps of the kind: `dates` gives the completion date of the first
// steps (null = pending), `comments` the optional comment per step.
const timeline = (kind, dates = [], comments = {}) => {
  const steps = REFERENTIALS.processingSteps[kind];
  // Three dates on a five-step circuit means the order went all the way through: fill the rest.
  const all = dates.length >= 3 && dates.length < steps.length ? [...dates, ...Array(steps.length - dates.length).fill(dates[dates.length - 1])] : dates;
  return steps.map((step, i) => ({ step, at: all[i] || null, done: !!all[i], comment: comments[step] || '' }));
};

